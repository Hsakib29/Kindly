// Generates extension icons from assets/source/ into public/icons/,
// plus src/shared/assets.ts embedding the floating glyph as a data URI
// so the content script needs no web_accessible_resources entry.
// Run via `npm run icons` (also chained into build/dev).
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(root, 'assets', 'source');
const OUT = resolve(root, 'public', 'icons');
const ASSETS_TS = resolve(root, 'src', 'shared', 'assets.ts');

const KERNEL = 'lanczos3'; // high-quality downscaling

const MAIN_SIZES = [16, 32, 48, 128];
const FLOATING_SIZES = [64, 128];

mkdirSync(OUT, { recursive: true });

for (const size of MAIN_SIZES) {
  const out = resolve(OUT, `icon-${size}.png`);
  await sharp(resolve(SRC, 'icon-main.png'))
    .resize(size, size, { kernel: KERNEL })
    .png({ compressionLevel: 9 })
    .toFile(out);
  console.log(`icon-${size}.png`);
}

const floatingDataUris = {};
for (const size of FLOATING_SIZES) {
  const buffer = await sharp(resolve(SRC, 'icon-floating.png'))
    .resize(size, size, { kernel: KERNEL })
    .png({ compressionLevel: 9 })
    .toBuffer();
  const out = resolve(OUT, `floating-${size}.png`);
  writeFileSync(out, buffer);
  floatingDataUris[size] = `data:image/png;base64,${buffer.toString('base64')}`;
  console.log(`floating-${size}.png`);
}

// Embedded copy for the Shadow DOM icon (P2.3). Generated — do not edit by hand.
const assetsTs = `// GENERATED by scripts/make-icons.mjs — do not edit.
// Data-URI copies of public/icons/floating-*.png so the content script can
// render the on-page icon inside its Shadow DOM without web_accessible_resources.
// Used by the floating field icon (P2.3/P2.4).

export const FLOATING_ICON_64_DATA_URI = '${floatingDataUris[64]}';
export const FLOATING_ICON_128_DATA_URI = '${floatingDataUris[128]}';
`;
writeFileSync(ASSETS_TS, assetsTs);
console.log('src/shared/assets.ts');
